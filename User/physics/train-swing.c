/* Episodic policy search using the cross-entropy method. Rebuild with
 * cc -O3 train-swing.c -lm -o train-swing. stdout is the frozen C policy;
 * progress and evaluation are written to stderr. */
#include "swing.h"
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>

enum { POP=56, ELITE=9, GENERATIONS=50, STEPS=8*120 };
typedef struct { double w[SWING_PARAMS],reward; } Candidate;
typedef struct { int stable; double reward; } Result;
static uint32_t random_state=0x3ab97c51;
static double uniform(void) {
    random_state^=random_state<<13; random_state^=random_state>>17; random_state^=random_state<<5;
    return (random_state+0.5)/4294967296.;
}
static double normal(void) { return sqrt(-2*log(uniform()))*cos(2*swing_pi*uniform()); }
static Result episode(const double *w,const double tilt[3]) {
    Mechanism m;
    hanging_scene(&m,tilt);
    int held=0;
    double reward=0;
    for (int t=0;t<STEPS;++t) {
        double torque[3];
        double cost=swing_action(&m,w,torque);
        motor_step(&m,torque,1./120);
        if (t%4==3) {
            double align=0, speed=0;
            for (int i=0;i<3;++i) {
                Link *l=&m.links[i]; align-=cos(swing_angle(l)); speed+=fmin(36,l->omega*l->omega);
            }
            int stable=swing_upright(&m);
            held=stable?held+4:0;
            reward+=(1+t/(double)STEPS)*(align+stable*.9-speed*.004-cost*.006);
        }
    }
    return (Result){held,reward};
}
static int descending(const void *a,const void *b) {
    double x=((const Candidate *)a)->reward,y=((const Candidate *)b)->reward;
    return (x<y)-(x>y);
}
int main(void) {
    Candidate population[POP],champion={.reward=-1e30};
    double mean[SWING_PARAMS]={0},sd[SWING_PARAMS];
    for (int i=0;i<SWING_PARAMS;++i) {
        /* Broad search with local stiffness/damping as the prior. All final
         * gains, including cross-link feedback, are selected by episode return. */
        int k=i%SWING_FEATURES;
        mean[i]=k==0?1.3:k==1?.4:0;
        sd[i]=k==0?1.0:k==1?.35:k==3||k==5?.17:.55;
    }
    const double down[3]={0};
    for (int gen=0;gen<GENERATIONS;++gen) {
        double perturbed[3];
        for (int i=0;i<3;++i) perturbed[i]=(uniform()-.5)*.18;
        for (int p=0;p<POP;++p) {
            Candidate *c=&population[p];
            for (int i=0;i<SWING_PARAMS;++i)
                c->w[i]=p==0?mean[i]:mean[i]+sd[i]*normal();
            c->reward=episode(c->w,perturbed).reward;
        }
        qsort(population,POP,sizeof population[0],descending);
        for (int i=0;i<SWING_PARAMS;++i) {
            double avg=0,var=0;
            for (int p=0;p<ELITE;++p) avg+=population[p].w[i]/ELITE;
            for (int p=0;p<ELITE;++p) { double d=population[p].w[i]-avg; var+=d*d/ELITE; }
            mean[i]=.25*mean[i]+.75*avg;
            sd[i]=fmax(.018,.25*sd[i]+.75*sqrt(var));
        }
        Result r=episode(population[0].w,down);
        if (r.reward>champion.reward) {
            champion=population[0]; champion.reward=r.reward;
        }
        fprintf(stderr,"generation %d return %.1f held %.2fs\n",gen+1,r.reward,r.stable/120.);
    }
    /* Disjoint RNG stream and wider perturbations for held-out evaluation. */
    random_state=0xf23a9cd1;
    int successes=0;
    for (int run=0;run<32;++run) {
        double tilt[3];
        for (int i=0;i<3;++i) tilt[i]=(2*uniform()-1)*10*swing_pi/180;
        Result r=episode(champion.w,tilt); successes+=r.stable>=240;
    }
    Result release=episode(champion.w,down);
    fprintf(stderr,"held-out %d/32; zero-start final hold %.2fs; return %.1f\n",successes,release.stable/120.,release.reward);
    puts("/* Generated by train-swing.c, deterministic CEM seed 0x3ab97c51. */");
    puts("static const double swing_weights[SWING_PARAMS]={");
    for (int i=0;i<3;++i) {
        for (int j=0;j<SWING_FEATURES;++j) printf(" %.17g,",champion.w[i*SWING_FEATURES+j]);
        puts("");
    }
    puts("};");
    return release.stable<240 || successes<30;
}

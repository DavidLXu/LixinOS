"""Replay the measured runs, verify their CSV metrics and emit the Win3 catalog."""
import csv
import os
import subprocess
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

base = Path(__file__).resolve().parent
seeds = [0x3AB97C51, 0x91C706AD, 0x2E0FB349]
rows = []
for filename in ("swing-orders-results.csv", "swing-orders-1200-results.csv"):
    with (base / filename).open() as source:
        rows.extend(csv.DictReader(source))

with tempfile.TemporaryDirectory() as directory:
    exe = Path(directory) / "train"
    subprocess.run([os.environ.get("CC", "cc"), "-std=c11", "-O3",
                    base / "swing-orders.c", "-lm", "-o", exe], check=True)

    def export(row):
        args = [row[key] for key in ("order", "seed", "budget_generations")]
        weights = Path(directory) / "-".join(args)
        output = subprocess.check_output([exe, *args, weights], text=True)
        result = dict(zip(row, next(csv.reader([output.strip()]))))
        for key in row.keys() - {"wall_seconds"}:
            if row[key] != result[key]:
                raise ValueError(f"{args}: {key} expected {row[key]}, got {result[key]}")
        lines = weights.read_text().splitlines()
        assert len(lines) == int(row["order"]) and all(len(line.split()) == 7 for line in lines)
        return row, lines

    # Show the best validation result first. Keep training budgets and seeds distinct.
    rows.sort(key=lambda r: (int(r["order"]), -int(r["passed_validation"]),
                             -int(r["validation_successes_of_16"]), -int(r["budget_generations"]),
                             seeds.index(int(r["seed"]))))
    with ThreadPoolExecutor(12) as pool:
        results = list(pool.map(export, rows))

print("/* Generated by benchmark/export-presets.py from the two benchmark CSVs. */")
print("static const SwingPreset swing_presets[]={")
print('    {3,0,50,32,swing_weights}, /* Original three-link demonstration. */')
for row, lines in results:
    seed = seeds.index(int(row["seed"])) + 1
    print("    {%s,%s,%s,%s,(const double[]){" % (
        row["order"], seed, row["generations_run"], row["test_successes_of_32"]))
    for line in lines:
        print("        " + ",".join(line.split()) + ",")
    print("    }},")
print("};")

"""Regenerate launcher-pinyin.h with ICU's uconv (Homebrew icu4c on macOS)."""
from pathlib import Path
import re
import subprocess
import sys

chars = "\n".join(map(chr, range(0x3400, 0xA000)))
readings = subprocess.run(
    [sys.argv[1] if len(sys.argv) > 1 else "uconv", "-x", "Han-Latin; Latin-ASCII; Lower"],
    input=chars, capture_output=True, text=True, check=True,
).stdout.splitlines()
assert len(readings) == 0xA000 - 0x3400
syllables = [""] + sorted({s for s in readings if re.fullmatch("[a-z]+", s)})
ids = {s: i for i, s in enumerate(syllables)}
with Path(__file__).with_name("launcher-pinyin.h").open("w") as f:
    print("/* Generated by generate-launcher-pinyin.py from ICU Han-Latin. */", file=f)
    print(f"typedef struct {{ char syllables[{len(syllables)}][8]; unsigned short index[0x6c00]; }} LauncherPinyin;", file=f)
    print("#ifndef LX_NETSURF\nstatic const LauncherPinyin launcher_dictionary = {{", file=f)
    assert max(map(len, syllables)) < 8
    for i in range(0, len(syllables), 12):
        print(",".join('"' + s + '"' for s in syllables[i:i+12]) + ",", file=f)
    print("},{", file=f)
    for i in range(0, len(readings), 32):
        print(",".join(str(ids.get(s, 0)) for s in readings[i:i+32]) + ",", file=f)
    print("}};\n#endif", file=f)
